'''
FFA Rules
- One shared deck
- Each player chooses a Leader (no repeats)
    - The Shadow Claw cannot be used in a 1v1
- Each player draws 5 cards to start
- On your turn, you start with 3 AP that you can spend in the following ways:
For 1 AP:
    - Draw a card
    - Play a Hero/Item/Magic Card from your hand
    - Activate a Hero effect (that hasn't been activated this turn)
More than 1 AP:
    - 2 AP to attack a Monster
    - 3 AP to discard your hand and draw 5 cards
    - Activate a Leader ability (0-2 AP)
- Any effect allowing you to immediately play a card does not require AP
- You can play Items and Curses to any Hero belonging to any player, but the max number of items on a hero is 1
- Modifiers can be played on any roll to either increase or decrease the roll value.
- You can wait for a player to choose the target of their effect before using modifiers
- Challenge cards are used when a player plays a Hero/Item/Magic card from their hand. Multiple challenges cannot be used on the same card
- When challenging, both players roll two dice and the higher roll wins.
- If you win the challenge, their card is sent to the discard pile immediately

- Your turn ends when you run out of AP or choose to end your turn

- You win by either having a party with 6 different classes of Heroes or you have slain 3 Monsters
    - Your Leader counts towards having 6 different classes
- There is no limit to the number of heroes in your party.
- To attack, you first need enough heroes to meet the requirements to attack. Each hero in your party counts once to the requirement.
- Your party leader does not count towards the requirements for attacking

'''